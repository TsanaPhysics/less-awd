                    <span>การทำนาเปียกสลับแห้ง (AWD) ทำให้ผลผลิตข้าวลดลงหรือไม่?</span>
                </h3>
                <p class="text-xs text-gray-600 leading-relaxed pl-8">
                    <strong>ไม่ลดลง และมักได้ผลผลิตเพิ่มขึ้น 10-15%</strong> เนื่องจากการปล่อยให้น้ำแห้งจะทำให้อากาศและออกซิเจนซึมลงสู่ชั้นดิน 
                    กระตุ้นให้รากข้าวหยั่งลึกลงไปหาความชื้น ลำต้นแข็งแรง ไม่ล้มง่ายเมื่อมีลมพายุ ลดการระบาดของโรคแมลงและเพลี้ยกระโดดสีน้ำตาล
                </p>
