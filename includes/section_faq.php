                    <span>ช่วงการเจริญเติบโตใดของข้าวที่ "ห้ามปล่อยให้น้ำแห้ง"?</span>
                </h3>
                <p class="text-xs text-gray-600 leading-relaxed pl-8">
                    <strong>ช่วงตั้งท้องจนถึงออกรวงและผสมเกสร (ประมาณวันที่ 60-85 หลังหว่าน/ปักดำ)</strong> เป็นช่วงวิกฤตที่ต้นข้าวต้องการน้ำอย่างต่อเนื่อง 
                    ต้องรักษาระดับน้ำขังไว้ที่ประมาณ +5 ถึง +10 cm เพื่อให้รวงข้าวผสมเกสรสมบูรณ์ เมล็ดเต่ง ไม่ลีบ
                </p>
