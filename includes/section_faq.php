                    <span>ทำไมต้องกำหนดเกณฑ์น้ำแห้งไว้ที่ -15 cm จากผิวดิน?</span>
                </h3>
                <p class="text-xs text-gray-600 leading-relaxed pl-8">
                    ระดับความลึก <strong>-15 cm</strong> คือเกณฑ์ความปลอดภัยทางสรีรวิทยาของต้นข้าว (Safe Alternate Wetting and Drying) 
                    ซึ่งรากฝอยยังสามารถดูดซับความชื้นผ่านแรงดึงของเม็ดดิน (Capillary Action) ได้เต็มที่โดยไม่เกิดสภาวะเครียดจากการขาดน้ำ
                </p>
            </div>

            <div class="glass-card p-5 rounded-2xl border border-gray-200 shadow-sm space-y-2">
